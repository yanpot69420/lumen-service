import type {
  AuditEntry,
  CashEntry,
  Correction,
  Customer,
  DayClose,
  Part,
  Setting,
  Ticket,
  Unit,
  User,
} from "./types";

/* eslint-disable @typescript-eslint/no-explicit-any */

// ---- Konversi nilai ----
const iso = (ms: number) => new Date(ms).toISOString();
const ms = (s: string | null | undefined) => (s ? Date.parse(s) : undefined);
const b2n = (b: unknown): 1 | 0 => (b ? 1 : 0);
const opt = <T>(v: T | null | undefined) => (v === null ? undefined : v);

interface Mapper {
  remote: string; // nama tabel Supabase
  toRemote: (row: any) => any;
  toLocal: (row: any) => any;
}

// ---- Registry pemetaan tiap tabel Dexie → Supabase ----
export const M: Record<string, Mapper> = {
  users: {
    remote: "users",
    toRemote: (u: User) => ({
      id: u.id,
      name: u.name,
      username: u.username,
      role: u.role,
      active: !!u.active,
      created_at: iso(u.createdAt),
    }),
    toLocal: (r: any): User => ({
      id: r.id,
      name: r.name,
      username: r.username,
      role: r.role,
      pinHash: "",
      pinVer: r.pin_ver ?? 2,
      salt: "",
      recoveryHash: undefined,
      recoverySalt: undefined,
      recoveryActive: r.has_recovery,
      active: b2n(r.active),
      createdAt: ms(r.created_at) ?? Date.now(),
    }),
  },
  settings: {
    remote: "settings",
    toRemote: (s: Setting) => ({ key: s.key, value: s.value }),
    toLocal: (r: any): Setting => ({ key: r.key, value: r.value }),
  },
  customers: {
    remote: "customers",
    toRemote: (c: Customer) => ({
      id: c.id,
      name: c.name,
      phone: c.phone,
      phone_normalized: c.phoneNormalized,
      notes: c.notes,
      is_regular: c.isRegular,
      created_at: iso(c.createdAt),
      updated_at: iso(c.updatedAt),
      created_by: c.createdBy,
    }),
    toLocal: (r: any): Customer => ({
      id: r.id,
      name: r.name,
      phone: r.phone,
      phoneNormalized: r.phone_normalized,
      notes: r.notes,
      isRegular: !!r.is_regular,
      createdAt: ms(r.created_at) ?? Date.now(),
      updatedAt: ms(r.updated_at) ?? Date.now(),
      createdBy: r.created_by,
    }),
  },
  tickets: {
    remote: "tickets",
    toRemote: (t: Ticket) => ({
      id: t.id,
      customer_id: t.customerId ?? null,
      no_nota: t.noNota,
      garansi_dari: t.garansiDari ?? null,
      piutang: t.piutang ?? 0,
      customer_name: t.customerName,
      phone: t.phone,
      brand: t.brand,
      model: t.model,
      keluhan: t.keluhan,
      kelengkapan: t.kelengkapan,
      estimasi: t.estimasi,
      biaya_jasa: t.biayaJasa,
      harga_final: t.hargaFinal ?? t.biayaJasa > 0,
      dp: t.dp,
      status: t.status,
      history: t.history,
      parts_used: t.partsUsed,
      created_by: t.createdBy,
      created_at: iso(t.createdAt),
      updated_at: iso(t.updatedAt),
    }),
    toLocal: (r: any): Ticket => ({
      id: r.id,
      ...(r.customer_id ? { customerId: r.customer_id } : {}),
      noNota: r.no_nota,
      garansiDari: opt(r.garansi_dari),
      piutang: r.piutang ?? 0,
      customerName: r.customer_name,
      phone: r.phone,
      brand: r.brand,
      model: r.model,
      keluhan: r.keluhan,
      kelengkapan: r.kelengkapan ?? [],
      estimasi: r.estimasi,
      biayaJasa: r.biaya_jasa,
      hargaFinal: r.harga_final,
      dp: r.dp,
      status: r.status,
      history: r.history ?? [],
      partsUsed: r.parts_used ?? [],
      createdAt: ms(r.created_at) ?? Date.now(),
      updatedAt: ms(r.updated_at) ?? Date.now(),
      createdBy: r.created_by,
    }),
  },
  units: {
    remote: "units",
    toRemote: (u: Unit) => ({
      id: u.id,
      kode: u.kode,
      brand: u.brand,
      model: u.model,
      varian: u.varian,
      imei: u.imei,
      kondisi: u.kondisi,
      harga_beli: u.hargaBeli,
      harga_jual: u.hargaJual,
      status: u.status,
      seller_name: u.sellerName,
      seller_phone: u.sellerPhone,
      garansi_hari: u.garansiHari,
      bought_at: iso(u.boughtAt),
      sold_at: u.soldAt ? iso(u.soldAt) : null,
      sold_price: u.soldPrice ?? null,
      buyer_name: u.buyerName ?? null,
      buyer_phone: u.buyerPhone ?? null,
      created_by: u.createdBy,
    }),
    toLocal: (r: any): Unit => ({
      id: r.id,
      kode: r.kode,
      brand: r.brand,
      model: r.model,
      varian: r.varian,
      imei: r.imei,
      kondisi: r.kondisi,
      hargaBeli: r.harga_beli,
      hargaJual: r.harga_jual,
      status: r.status,
      sellerName: r.seller_name,
      sellerPhone: r.seller_phone,
      garansiHari: r.garansi_hari,
      boughtAt: ms(r.bought_at) ?? Date.now(),
      soldAt: ms(r.sold_at),
      soldPrice: opt(r.sold_price),
      buyerName: opt(r.buyer_name),
      buyerPhone: opt(r.buyer_phone),
      createdBy: r.created_by,
    }),
  },
  parts: {
    remote: "parts",
    toRemote: (p: Part) => ({
      id: p.id,
      nama: p.nama,
      brand: p.brand ?? null,
      kategori: p.kategori,
      stok: p.stok,
      harga_modal: p.hargaModal,
      harga_jual: p.hargaJual,
      min_stok: p.minStok,
    }),
    toLocal: (r: any): Part => ({
      id: r.id,
      nama: r.nama,
      ...(typeof r.brand === "string" ? { brand: r.brand } : {}),
      kategori: r.kategori,
      stok: r.stok,
      hargaModal: r.harga_modal,
      hargaJual: r.harga_jual,
      minStok: r.min_stok,
    }),
  },
  cash: {
    remote: "cash_entries",
    toRemote: (c: CashEntry) => ({
      id: c.id,
      at: iso(c.at),
      day_key: c.dayKey,
      type: c.type,
      category: c.category,
      method: c.method ?? "tunai",
      amount: c.amount,
      note: c.note,
      ref_type: c.refType ?? null,
      ref_id: c.refId ?? null,
      meta: c.meta ?? null,
      by_user: c.by,
      by_name: c.byName,
      locked: !!c.locked,
      voided: !!c.voided,
    }),
    toLocal: (r: any): CashEntry => ({
      id: r.id,
      at: ms(r.at) ?? Date.now(),
      dayKey: r.day_key,
      type: r.type,
      category: r.category,
      method: r.method ?? "tunai",
      amount: r.amount,
      note: r.note,
      refType: opt(r.ref_type),
      refId: opt(r.ref_id),
      meta: opt(r.meta),
      by: r.by_user,
      byName: r.by_name,
      locked: b2n(r.locked),
      voided: b2n(r.voided),
    }),
  },
  dayCloses: {
    remote: "day_closes",
    toRemote: (d: DayClose) => ({
      day_key: d.dayKey,
      expected: d.expected,
      counted: d.counted,
      selisih: d.selisih,
      note: d.note,
      closed_by: d.closedBy,
      closed_by_name: d.closedByName,
      closed_at: iso(d.closedAt),
    }),
    toLocal: (r: any): DayClose => ({
      dayKey: r.day_key,
      expected: r.expected,
      counted: r.counted,
      selisih: r.selisih,
      note: r.note,
      closedBy: r.closed_by,
      closedByName: r.closed_by_name,
      closedAt: ms(r.closed_at) ?? Date.now(),
    }),
  },
  corrections: {
    remote: "corrections",
    toRemote: (k: Correction) => ({
      id: k.id,
      at: iso(k.at),
      entity: k.entity,
      entity_id: k.entityId,
      reason: k.reason,
      before_data: k.before,
      after_data: k.after,
      requested_by: k.requestedBy,
      requested_by_name: k.requestedByName,
      status: k.status,
      decided_by: k.decidedBy ?? null,
      decided_by_name: k.decidedByName ?? null,
      decided_at: k.decidedAt ? iso(k.decidedAt) : null,
    }),
    toLocal: (r: any): Correction => ({
      id: r.id,
      at: ms(r.at) ?? Date.now(),
      entity: r.entity,
      entityId: r.entity_id,
      reason: r.reason,
      before: r.before_data,
      after: r.after_data,
      requestedBy: r.requested_by,
      requestedByName: r.requested_by_name,
      status: r.status,
      decidedBy: opt(r.decided_by),
      decidedByName: opt(r.decided_by_name),
      decidedAt: ms(r.decided_at),
    }),
  },
  photos: {
    remote: "photos",
    toRemote: (p: any) => ({ id: p.id, ref_type: p.refType, ref_id: p.refId, path: p.remotePath ?? `${p.id}.jpg`, created_at: iso(p.createdAt), deleted: false }),
    toLocal: (r: any) => ({ id: r.id, refType: r.ref_type, refId: r.ref_id, remotePath: r.path, createdAt: ms(r.created_at) ?? Date.now() }),
  },
  audit: {
    remote: "audit_log",
    toRemote: (a: AuditEntry) => ({
      id: a.id,
      at: iso(a.at),
      user_id: a.userId,
      user_name: a.userName,
      action: a.action,
      entity: a.entity,
      entity_id: a.entityId,
      summary: a.summary,
    }),
    toLocal: (r: any): AuditEntry => ({
      id: r.id,
      at: ms(r.at) ?? Date.now(),
      userId: r.user_id,
      userName: r.user_name,
      action: r.action,
      entity: r.entity,
      entityId: r.entity_id,
      summary: r.summary,
    }),
  },
};
