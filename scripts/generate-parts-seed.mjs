import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../src/db/seeds/spareparts.json", import.meta.url);
const target = new URL("../supabase/seed.sql", import.meta.url);
const catalog = JSON.parse(await readFile(source, "utf8"));
const ids = new Set();
const names = new Set();
for (const row of catalog) {
  const name = row.nama?.trim().replace(/\s+/g, " ").toLowerCase();
  if (!/^[\da-f]{8}-[\da-f]{4}-[\da-f]{4}-[\da-f]{4}-[\da-f]{12}$/i.test(row.id)
      || !name || typeof row.brand !== "string" || !row.brand.trim() || row.brand.length > 50 || !Number.isSafeInteger(row.minStok) || row.minStok < 0
      || ids.has(row.id) || names.has(name)) {
    throw new Error(`Baris seed tidak valid/duplikat: ${JSON.stringify(row)}`);
  }
  ids.add(row.id);
  names.add(name);
}
if (!catalog.length) throw new Error("Katalog seed kosong");
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const values = catalog.map((row) => `  (${quote(row.id)}::uuid, ${quote(row.nama)}, ${quote(row.brand)}, ${row.minStok})`).join(",\n");
const sql = `-- Generated by npm run seed:generate from src/db/seeds/spareparts.json.
-- Starter catalog only: no inventory value, payments, users or demo transactions.
-- Run against an installed Lumen schema as administrator; safe to run again.
begin;
lock table public.parts in share row exclusive mode;
with catalog(id,nama,brand,min_stok) as (values
${values}
)
insert into public.parts(id,nama,brand,kategori,stok,harga_modal,harga_jual,min_stok)
select c.id,c.nama,c.brand,'sparepart',0,0,0,c.min_stok
from catalog c
where not exists (
  select 1 from public.parts p
  where p.kategori='sparepart'
    and lower(regexp_replace(btrim(p.nama),'\\s+',' ','g'))=lower(regexp_replace(btrim(c.nama),'\\s+',' ','g'))
)
on conflict (id) do nothing;
commit;
`;
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== sql) {
    throw new Error("supabase/seed.sql tertinggal. Jalankan npm run seed:generate.");
  }
  console.log(`Seed sinkron: ${catalog.length} sparepart.`);
} else {
  await writeFile(target, sql);
  console.log(`supabase/seed.sql dibuat: ${catalog.length} sparepart.`);
}
